/**
 * מה שהמעטפת (פס הכותרת ושורת המצב) מציגה — כפונקציות טהורות.
 *
 * למה מודול ולא ליטרל בתבנית: הכללים כאן הם החלטות שאפשר לטעות בהן בשקט —
 * רוחב שדה שחותך שם עברי ארוך, ומשפט „עמוד 1 מתוך 1” שמוצג על מסמך שאיש לא
 * מדד. בקוד של קומפוננטה אין דרך לבדוק אותם בלי להרים DOM; כאן הם קלט־פלט.
 *
 * הכלל שחוזר בכל הפונקציות: **מה שלא נמדד לא מוצג.** כל פונקציה כאן מקבלת גם
 * „לא ידוע” (`null`) ומחזירה עליו נוסח מצומצם או מחרוזת ריקה — ולא מספר
 * שנראה אמיתי.
 */

/** רוחב מינימלי לשדה שם המסמך, ב-ch. גם „א” צריך להיראות כמו שדה. */
export const DOC_TITLE_MIN_CH = 8;

/**
 * התקרה. שם ארוך נחתך בשדה עצמו (הוא `input`) ולא דוחק את שאר הפס: פס הכותרת
 * הוא גריד של שלוש עמודות שוות־קצה, ותיבת החיפוש שבמרכזו חייבת להישאר במרכז
 * החלון בלי תלות באורך השם.
 */
export const DOC_TITLE_MAX_CH = 30;

/**
 * רוחב שדה שם המסמך ב-ch, לפי אורך השם.
 *
 * `width: 110px` קשיח שהיה כאן חתך „חידושים על מסכת בבא מציעא” אחרי שש אותיות.
 * ה-ch נגזר מרוחב הספרה „0” בגופן של השדה; עברית צרה ממנה, ולכן התוספת של
 * תו אחד מספיקה כדי שהסמן לא ידבק לקצה.
 */
export function docTitleWidthCh(title: string): number {
  const length = title.trim().length;
  return Math.min(DOC_TITLE_MAX_CH, Math.max(DOC_TITLE_MIN_CH, length + 1));
}
